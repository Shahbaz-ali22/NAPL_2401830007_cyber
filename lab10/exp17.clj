(println "--- 1. LIST ---")
(def l (list 1 2 3 4))
(println "first:" (first l))
(println "rest:" (rest l))
(def new-l (conj l 0))
(println "original:" l)
(println "new:" new-l)

(println "\n--- 2. VECTOR ---")
(def v [10 20 30 40])
(println "get index 1:" (get v 1))
(println "count:" (count v))
(def new-v (conj v 50))
(println "original:" v)
(println "new:" new-v)

(println "\n--- 3. MAP ---")
(def m {:name "Alice" :age 20})
(println "get name:" (get m :name))
(def m-assoc (assoc m :city "Delhi"))
(def m-dissoc (dissoc m :age))
(println "original:" m)
(println "after assoc:" m-assoc)
(println "after dissoc:" m-dissoc)

(println "\n--- 4. SET ---")
(def s #{1 2 3})
(println "contains 2?:" (contains? s 2))
(def s-conj (conj s 4))
(def s-disj (disj s 1))
(println "original:" s)
(println "after conj:" s-conj)
(println "after disj:" s-disj)
